import { dirname } from "node:path";
import { fileURLToPath } from "node:url";
import react from "@vitejs/plugin-react";
import { loadEnv, type Plugin } from "vite";
import { defineConfig } from "vitest/config";
import { buildMetaContent, readDefaultReportUrl, resolveBuildIdentity, resolveReportUrlSetting, type BuildIdentity } from "../../scripts/lib/build-identity.mjs";

const WEB_ROOT = dirname(fileURLToPath(import.meta.url));

/**
 * ADR-0010 §2 rule 4 / SEC-M3-003: determines whether a production bundle (`vite build`) may load unpublished
 * (`candidate` / `validated`) datasets.
 * - On Cloudflare Pages (`CF_PAGES=1`) or Workers Builds (`WORKERS_CI=1`), only a non-production preview branch
 *   may enable it; the production branch (`PRODUCTION_BRANCH`, default `"main"`) is always `false` regardless of
 *   dashboard environment variables (`VITE_ALLOW_UNPUBLISHED` or `NODE_ENV`).
 * - Outside preview CI, `vite build` defaults to `false` unless `VITE_ALLOW_UNPUBLISHED === "true"` is explicitly set.
 */
export function resolveBuildAllowUnpublished(env: Record<string, string | undefined> = process.env): boolean {
  const prodBranch = env.PRODUCTION_BRANCH?.trim() || "main";
  if (env.CF_PAGES === "1" || env.WORKERS_CI === "1") {
    const branch = (env.CF_PAGES_BRANCH ?? env.WORKERS_CI_BRANCH)?.trim();
    return Boolean(branch && branch !== prodBranch && env.VITE_ALLOW_UNPUBLISHED !== "false");
  }
  return env.VITE_ALLOW_UNPUBLISHED === "true";
}

/** ADR-0010 §4. Build only: the dev server needs inline scripts for hot reload. */
const CSP = [
  "default-src 'self'",
  "script-src 'self'",
  "style-src 'self'",
  "img-src 'self' data: blob:",
  "font-src 'self'",
  "connect-src 'self'",
  "worker-src 'self'",
  "manifest-src 'self'",
  "object-src 'none'",
  "base-uri 'none'",
  "form-action 'none'",
].join("; ");

function contentSecurityPolicy(): Plugin {
  return {
    name: "ky-nay-csp",
    apply: "build",
    transformIndexHtml(html) {
      return html.replace('<meta charset="UTF-8" />', `<meta charset="UTF-8" />\n    <meta http-equiv="Content-Security-Policy" content="${CSP}" />`);
    },
  };
}

/**
 * SEC-M3-007: HTTP headers for the static host (Cloudflare Pages / Netlify `_headers` format), generated from the same
 * CSP so the two cannot drift. `frame-ancestors` only works as a header, never in the <meta> tag.
 */
export function deployHeaders(): string {
  return [
    "# Generated by apps/web/vite.config.ts at build time (SEC-M3-007). Do not edit by hand.",
    "/*",
    `  Content-Security-Policy: ${CSP}; frame-ancestors 'none'`,
    "  X-Frame-Options: DENY",
    "  X-Content-Type-Options: nosniff",
    "  Referrer-Policy: no-referrer",
    "  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=()",
    "  Strict-Transport-Security: max-age=31536000",
    "  Cross-Origin-Opener-Policy: same-origin",
    "/sw.js",
    "  Cache-Control: no-cache",
    "/data/manifest.json",
    "  Cache-Control: no-cache",
    "",
  ].join("\n");
}

function hostHeaders(): Plugin {
  return {
    name: "ky-nay-host-headers",
    apply: "build",
    generateBundle() {
      this.emitFile({ type: "asset", fileName: "_headers", source: deployHeaders() });
    },
  };
}

/** Parses the `_headers` text above into path rules (`/*` matches every path, any other entry one exact path). */
export function parseHeaderRules(text: string): { path: string; headers: [string, string][] }[] {
  const rules: { path: string; headers: [string, string][] }[] = [];
  for (const line of text.split("\n")) {
    if (line.trim() === "" || line.startsWith("#")) continue;
    if (!line.startsWith(" ")) {
      rules.push({ path: line.trim(), headers: [] });
      continue;
    }
    const rule = rules.at(-1);
    const colon = line.indexOf(":");
    if (!rule || colon < 0) throw new Error(`malformed _headers line: ${line}`);
    rule.headers.push([line.slice(0, colon).trim(), line.slice(colon + 1).trim()]);
  }
  return rules;
}

/**
 * M5-I: `vite preview` answers with the same headers as the static host, so scripts/smoke-deploy.mjs and the e2e
 * suite exercise the production header set locally (DESIGN-M5-001 §7). Preview only; the dev server is untouched.
 */
function previewHostHeaders(): Plugin {
  const rules = parseHeaderRules(deployHeaders());
  return {
    name: "ky-nay-preview-host-headers",
    configurePreviewServer(server) {
      server.middlewares.use((req, res, next) => {
        const path = new URL(req.url ?? "/", "http://preview.invalid").pathname;
        for (const rule of rules) {
          if (rule.path === "/*" || rule.path === path) for (const [name, value] of rule.headers) res.setHeader(name, value);
        }
        next();
      });
    },
  };
}

const escapeAttribute = (value: string): string => value.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

/** M5-A: `<meta name="ky-nay-build" content="<version>+<commit>">` lets the smoke script tell which build is served. */
function buildMeta(identity: BuildIdentity): Plugin {
  return {
    name: "ky-nay-build-meta",
    apply: "build",
    transformIndexHtml(html) {
      const tag = `<meta name="ky-nay-build" content="${escapeAttribute(buildMetaContent(identity))}" />`;
      if (!html.includes('<meta charset="UTF-8" />')) throw new Error("index.html lost its charset meta; cannot place ky-nay-build");
      return html.replace('<meta charset="UTF-8" />', `<meta charset="UTF-8" />\n    ${tag}`);
    },
  };
}

/**
 * M5-B / ADR-0014 point 4: `VITE_REPORT_ISSUE_URL` (process env or apps/web/.env*) is validated when the config loads;
 * an invalid value stops dev, test and build (fail closed). Unset → the committed default in
 * `report-issue.config.json` (B-05); `off` → `null` (copy-only report UI).
 */
export function resolveReportUrl(env: Record<string, string | undefined>, useCommittedDefault = true): string | null {
  try {
    return resolveReportUrlSetting(env.VITE_REPORT_ISSUE_URL, useCommittedDefault ? readDefaultReportUrl() : null);
  } catch (error) {
    throw new Error(`ky-nay: invalid VITE_REPORT_ISSUE_URL: ${(error as Error).message}`);
  }
}

/** Files copied from `public/` that belong to the app shell (datasets live in IndexedDB instead). */
const PUBLIC_SHELL = [
  "icon.svg",
  "manifest.webmanifest",
  // M5-G: PNG icons (scripts/generate-icons.mjs) are precached so an installed PWA keeps them offline.
  "icons/icon-192.png",
  "icons/icon-512.png",
  "icons/icon-maskable-512.png",
  "icons/apple-touch-icon.png",
];
/**
 * Build outputs never precached: host configuration, the worker itself, and `index.html`, which is cached as `./`.
 * Cloudflare Pages answers `/index.html` with a redirect to `/`, and a redirected response cannot serve a navigation.
 */
const NOT_PRECACHED = new Set(["sw.js", "_headers", "index.html"]);

/** Emits `sw.js` with this build's precache list; the cache name is a hash of the list (ADR-0010 §4). */
function serviceWorker(): Plugin {
  return {
    name: "ky-nay-service-worker",
    apply: "build",
    enforce: "post",
    generateBundle(_options, bundle) {
      const assets = Object.keys(bundle).filter((file) => !file.endsWith(".map") && !NOT_PRECACHED.has(file)).sort();
      const precache = ["./", ...[...assets, ...PUBLIC_SHELL].map((file) => `./${file}`)];
      const content = Object.values(bundle).map((item) => ("code" in item ? item.code : String(item.source))).join("");
      // The cache name changes whenever the precache list, any bundled file or the worker code changes.
      const version = createHash("sha256").update(precache.join("\n")).update(content).update(workerSource("", precache)).digest("hex").slice(0, 16);
      this.emitFile({ type: "asset", fileName: "sw.js", source: workerSource(version, precache) });
    },
  };
}

function workerSource(version: string, precache: readonly string[]): string {
  return `/* Kỳ Này service worker — generated at build time (ADR-0010 §4). */
const CACHE = "ky-nay-shell-${version}";
const PRECACHE = ${JSON.stringify(precache)};
self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)));
});
self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((key) => key.startsWith("ky-nay-shell-") && key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});
self.addEventListener("message", (event) => {
  if (event.data === "SKIP_WAITING") self.skipWaiting();
  if (event.data === "REPOPULATE_PRECACHE") {
    event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)));
  }
});
self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin || url.pathname.includes("/data/")) return;
  if (request.mode === "navigate") {
    // Offline: the shell cached as "./". A host may have redirected it; a redirected response cannot answer a
    // navigation (net::ERR_FAILED), so a copy without the redirect flag is returned.
    event.respondWith(fetch(request).catch(() => caches.open(CACHE).then((cache) => cache.match("./")).then((hit) => {
      if (!hit) return Response.error();
      return hit.redirected ? new Response(hit.body, { status: hit.status, statusText: hit.statusText, headers: hit.headers }) : hit;
    })));
    return;
  }
  // Assets are content-hashed, so Vary (e.g. Origin on crossorigin module scripts) can be ignored.
  event.respondWith(caches.open(CACHE).then((cache) => cache.match(request, { ignoreVary: true })).then((hit) => hit || fetch(request)));
});
`;
}

export default defineConfig(({ command, mode }) => {
  const isBuild = command === "build";
  const allowUnpublished = isBuild ? resolveBuildAllowUnpublished(process.env) : undefined;
  if (isBuild) {
    process.env.VITE_ALLOW_UNPUBLISHED = allowUnpublished ? "true" : "false";
    process.env.NODE_ENV = "production";
  }
  // M5-A/M5-B: defined in every mode (dev, build, vitest); apps/web/src/app/build-info.ts is the only reader.
  const identity = resolveBuildIdentity(process.env);
  // Vitest stays hermetic: only an explicit VITE_REPORT_ISSUE_URL applies there, never the committed default.
  const reportUrl = resolveReportUrl(loadEnv(mode, WEB_ROOT, "VITE_"), mode !== "test");
  return {
    base: "./",
    define: {
      __KY_NAY_BUILD__: JSON.stringify(identity),
      __KY_NAY_REPORT_URL__: JSON.stringify(reportUrl),
      ...(isBuild
        ? {
            "import.meta.env.VITE_ALLOW_UNPUBLISHED": JSON.stringify(allowUnpublished ? "true" : "false"),
            "import.meta.env.DEV": "false",
            "import.meta.env.PROD": "true",
          }
        : {}),
    },
    plugins: [react(), contentSecurityPolicy(), buildMeta(identity), hostHeaders(), previewHostHeaders(), serviceWorker()],
    build: {
      sourcemap: false,
      target: "es2022",
    },
    test: {
      environment: "jsdom",
      setupFiles: ["./src/test/setup.ts"],
      include: ["src/**/*.test.{ts,tsx}"],
      restoreMocks: true,
    },
  };
});
