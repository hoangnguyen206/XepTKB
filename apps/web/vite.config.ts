import { createHash } from "node:crypto";
import react from "@vitejs/plugin-react";
import type { Plugin } from "vite";
import { defineConfig } from "vitest/config";

/**
 * ADR-0010 §2 rule 4 / SEC-M3-003: determines whether a production bundle (`vite build`) may load unpublished
 * (`candidate` / `validated`) datasets.
 * - On Cloudflare Pages (`CF_PAGES=1`) or Workers Builds (`WORKERS_CI=1`), only a non-production preview branch
 *   may enable it; the production branch (`PRODUCTION_BRANCH`, default `"main"`) is always `false` regardless of
 *   dashboard environment variables (`VITE_ALLOW_UNPUBLISHED` or `NODE_ENV`).
 * - Outside preview CI, `vite build` defaults to `false` unless `VITE_ALLOW_UNPUBLISHED === "true"` is explicitly set.
 */
export function resolveBuildAllowUnpublished(env: Record<string, string | undefined> = process.env): boolean {
  const prodBranch = env.PRODUCTION_BRANCH?.trim() || "main";
  if (env.CF_PAGES === "1" || env.WORKERS_CI === "1") {
    const branch = (env.CF_PAGES_BRANCH ?? env.WORKERS_CI_BRANCH)?.trim();
    return Boolean(branch && branch !== prodBranch && env.VITE_ALLOW_UNPUBLISHED !== "false");
  }
  return env.VITE_ALLOW_UNPUBLISHED === "true";
}

/** ADR-0010 §4. Build only: the dev server needs inline scripts for hot reload. */
const CSP = [
  "default-src 'self'",
  "script-src 'self'",
  "style-src 'self'",
  "img-src 'self' data: blob:",
  "font-src 'self'",
  "connect-src 'self'",
  "worker-src 'self'",
  "manifest-src 'self'",
  "object-src 'none'",
  "base-uri 'none'",
  "form-action 'none'",
].join("; ");

function contentSecurityPolicy(): Plugin {
  return {
    name: "ky-nay-csp",
    apply: "build",
    transformIndexHtml(html) {
      return html.replace('<meta charset="UTF-8" />', `<meta charset="UTF-8" />\n    <meta http-equiv="Content-Security-Policy" content="${CSP}" />`);
    },
  };
}

/**
 * SEC-M3-007: HTTP headers for the static host (Cloudflare Pages / Netlify `_headers` format), generated from the same
 * CSP so the two cannot drift. `frame-ancestors` only works as a header, never in the <meta> tag.
 */
export function deployHeaders(): string {
  return [
    "# Generated by apps/web/vite.config.ts at build time (SEC-M3-007). Do not edit by hand.",
    "/*",
    `  Content-Security-Policy: ${CSP}; frame-ancestors 'none'`,
    "  X-Frame-Options: DENY",
    "  X-Content-Type-Options: nosniff",
    "  Referrer-Policy: no-referrer",
    "  Permissions-Policy: camera=(), microphone=(), geolocation=(), payment=(), usb=()",
    "  Strict-Transport-Security: max-age=31536000",
    "  Cross-Origin-Opener-Policy: same-origin",
    "/sw.js",
    "  Cache-Control: no-cache",
    "/data/manifest.json",
    "  Cache-Control: no-cache",
    "",
  ].join("\n");
}

function hostHeaders(): Plugin {
  return {
    name: "ky-nay-host-headers",
    apply: "build",
    generateBundle() {
      this.emitFile({ type: "asset", fileName: "_headers", source: deployHeaders() });
    },
  };
}

/** Files copied from `public/` that belong to the app shell (datasets live in IndexedDB instead). */
const PUBLIC_SHELL = ["icon.svg", "manifest.webmanifest"];
/**
 * Build outputs never precached: host configuration, the worker itself, and `index.html`, which is cached as `./`.
 * Cloudflare Pages answers `/index.html` with a redirect to `/`, and a redirected response cannot serve a navigation.
 */
const NOT_PRECACHED = new Set(["sw.js", "_headers", "index.html"]);

/** Emits `sw.js` with this build's precache list; the cache name is a hash of the list (ADR-0010 §4). */
function serviceWorker(): Plugin {
  return {
    name: "ky-nay-service-worker",
    apply: "build",
    enforce: "post",
    generateBundle(_options, bundle) {
      const assets = Object.keys(bundle).filter((file) => !file.endsWith(".map") && !NOT_PRECACHED.has(file)).sort();
      const precache = ["./", ...[...assets, ...PUBLIC_SHELL].map((file) => `./${file}`)];
      const content = Object.values(bundle).map((item) => ("code" in item ? item.code : String(item.source))).join("");
      // The cache name changes whenever the precache list, any bundled file or the worker code changes.
      const version = createHash("sha256").update(precache.join("\n")).update(content).update(workerSource("", precache)).digest("hex").slice(0, 16);
      this.emitFile({ type: "asset", fileName: "sw.js", source: workerSource(version, precache) });
    },
  };
}

function workerSource(version: string, precache: readonly string[]): string {
  return `/* Kỳ Này service worker — generated at build time (ADR-0010 §4). */
const CACHE = "ky-nay-shell-${version}";
const PRECACHE = ${JSON.stringify(precache)};
self.addEventListener("install", (event) => {
  event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)));
});
self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((key) => key.startsWith("ky-nay-shell-") && key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});
self.addEventListener("message", (event) => {
  if (event.data === "SKIP_WAITING") self.skipWaiting();
  if (event.data === "REPOPULATE_PRECACHE") {
    event.waitUntil(caches.open(CACHE).then((cache) => cache.addAll(PRECACHE)));
  }
});
self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin || url.pathname.includes("/data/")) return;
  if (request.mode === "navigate") {
    // Offline: the shell cached as "./". A host may have redirected it; a redirected response cannot answer a
    // navigation (net::ERR_FAILED), so a copy without the redirect flag is returned.
    event.respondWith(fetch(request).catch(() => caches.open(CACHE).then((cache) => cache.match("./")).then((hit) => {
      if (!hit) return Response.error();
      return hit.redirected ? new Response(hit.body, { status: hit.status, statusText: hit.statusText, headers: hit.headers }) : hit;
    })));
    return;
  }
  // Assets are content-hashed, so Vary (e.g. Origin on crossorigin module scripts) can be ignored.
  event.respondWith(caches.open(CACHE).then((cache) => cache.match(request, { ignoreVary: true })).then((hit) => hit || fetch(request)));
});
`;
}

export default defineConfig(({ command }) => {
  const isBuild = command === "build";
  const allowUnpublished = isBuild ? resolveBuildAllowUnpublished(process.env) : undefined;
  if (isBuild) {
    process.env.VITE_ALLOW_UNPUBLISHED = allowUnpublished ? "true" : "false";
    process.env.NODE_ENV = "production";
  }
  return {
    base: "./",
    ...(isBuild
      ? {
          define: {
            "import.meta.env.VITE_ALLOW_UNPUBLISHED": JSON.stringify(allowUnpublished ? "true" : "false"),
            "import.meta.env.DEV": "false",
            "import.meta.env.PROD": "true",
          },
        }
      : {}),
    plugins: [react(), contentSecurityPolicy(), hostHeaders(), serviceWorker()],
    build: {
      sourcemap: false,
      target: "es2022",
    },
    test: {
      environment: "jsdom",
      setupFiles: ["./src/test/setup.ts"],
      include: ["src/**/*.test.{ts,tsx}"],
      restoreMocks: true,
    },
  };
});
